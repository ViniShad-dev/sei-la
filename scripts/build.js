import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/app.js"],
  bundle: true,
  format: "iife",
  target: "es2020",
  write: false,
  minify: true,
  legalComments: "inline",
});
let css = await readFile(path.join(root, "src/style.css"), "utf8");
// Fonts are embedded too: Windows may extract only index.html when it is opened
// directly from the ZIP. No file:// imports, fetches or companion files are needed.
for (const font of ["serif", "sans"]) {
  const data = await readFile(path.join(root, `src/fonts/${font}.woff2`));
  css = css.replaceAll(
    `"./fonts/${font}.woff2"`,
    `"data:font/woff2;base64,${data.toString("base64")}"`,
  );
}
const script = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const html = `<!doctype html>
<!-- Generated by npm run build. Edit src/ and scripts/build.js, then rebuild. -->
<html lang="pt-BR">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="theme-color" content="#111311">
<meta name="description" content="Desperte a primeira chama. Um jogo incremental de forja, magia e criação.">
<title>Sword Clicker · Infinite Forge</title>
<style>${css.replaceAll("</style", "<\\/style")}</style>
</head>
<body>
<div id="app"><p style="padding:32px">Acendendo a forja…</p></div>
<noscript>Ative o JavaScript no navegador para jogar Sword Clicker.</noscript>
<script>${script}</script>
</body>
</html>
`;
await writeFile(path.join(root, "index.html"), html);
console.log(
  `index.html independente gerado: ${(Buffer.byteLength(html) / 1024).toFixed(1)} KB`,
);
